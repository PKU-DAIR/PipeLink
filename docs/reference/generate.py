"""Regenerate the clause and profile references from the live compiler."""

from __future__ import annotations

from contextlib import redirect_stdout
from dataclasses import fields
from io import StringIO
import json
from pathlib import Path

from pipec2.cli import main as pipec2_main
from pipec2.model import CLAUSE_PHASES
from pipec2.profile import PROFILES


HERE = Path(__file__).resolve().parent
COMMAND = "uv run --project pipec --locked python docs/reference/generate.py"
PHASE_ORDER = ("pack", "load", "layout", "protocol", "solve", "link", "launch")


def header(title: str, source: str) -> str:
    return (
        f"# {title}\n\n"
        f"Generated by [generate.py](generate.py) from {source}. "
        "Do not edit this file by hand.\n\n"
        "Regenerate from the repository root (no GPU required):\n\n"
        f"```sh\n{COMMAND}\n```\n\n"
    )


def table(headings: list[str], rows: list[list[str]]) -> str:
    def row(cells: list[str]) -> str:
        return "| " + " | ".join(
            cell.replace("|", "\\|").replace("\n", "<br>") for cell in cells
        ) + " |\n"

    return row(headings) + row(["---"] * len(headings)) + "".join(map(row, rows)) + "\n"


def value(item: object) -> str:
    if isinstance(item, (set, frozenset)):
        item = sorted(item)
    return f"`{json.dumps(item, ensure_ascii=False)}`"


def clauses() -> str:
    # Use the CLI itself: it imports all clause-registering modules. Its JSON
    # contains descriptions; primary phases are in the same populated registry.
    stdout = StringIO()
    with redirect_stdout(stdout):
        status = pipec2_main(["clauses", "--json"])
    if status:
        raise RuntimeError("pipec2 clauses --json failed")
    catalogue = json.loads(stdout.getvalue())
    text = header(
        "Clause catalogue",
        "`pipec2 clauses --json` (IDs and descriptions) and "
        "[`pipec2.model.CLAUSE_PHASES`](../../pipec/src/pipec2/model.py) "
        "(registered primary phases)",
    )
    text += (
        "A primary phase names the check inside the compiler, not necessarily the "
        "CLI command that reports it. For example, `link` also performs load, "
        "layout, protocol and solve checks. Clause IDs are extensible; this is "
        "the complete catalogue registered by the current CLI.\n\n"
    )
    phases = sorted({CLAUSE_PHASES[key] for key in catalogue}, key=PHASE_ORDER.index)
    for phase in phases:
        text += f"## {phase}\n\n"
        text += table(
            ["ID", "Primary phase", "Description"],
            [
                [f"`{key}`", f"`{phase}`", catalogue[key]]
                for key in sorted(catalogue)
                if CLAUSE_PHASES[key] == phase
            ],
        )
    return text


def profiles() -> str:
    profiles = [PROFILES[name] for name in sorted(PROFILES)]
    text = header("Target profiles", "[`pipec2.profile`](../../pipec/src/pipec2/profile.py)")
    text += (
        "These are the compiler's declared target contracts, not a claim that "
        "every example runs on every profile. `pack --profile` selects one; "
        "linked packages must agree on the target stamp. See the "
        "[coverage matrix](../index.md#mechanism--profile-coverage) and "
        "[compiler admission rules](../../pipec/README.md#target-profiles). "
        "Values below are taken directly from `PROFILES`, `Profile.arch`, "
        "`TargetCaps` and `Domain`; `null` means the field is absent.\n\n"
    )
    text += "## Names and targets\n\n"
    text += table(
        ["Profile", "Toolkit", "SM", "Compute", "Payload / adapter LTO", "Probe / stub LTO"],
        [
            [
                f"`{profile.name}`", f"`{profile.toolkit}`", f"`{profile.arch.sm}`",
                f"`{profile.arch.compute}`", f"`{profile.arch.lto}`", f"`{profile.arch.lto_base}`",
            ]
            for profile in profiles
        ],
    )
    names = [f"`{profile.name}`" for profile in profiles]
    text += "## Target caps\n\n"
    text += table(
        ["TargetCaps field", *names],
        [
            [f"`{field.name}`", *[value(getattr(profile.caps, field.name)) for profile in profiles]]
            for field in fields(profiles[0].caps)
        ],
    )
    text += "## Tensor and scheduling vocabulary\n\n"
    text += table(
        ["Profile field", *names],
        [
            [f"`{name}`", *[value(getattr(profile, name)) for profile in profiles]]
            for name in ("tmem_lanes", "catalogue", "schedulers", "scheduler_strategies", "fairness")
        ],
    )
    text += "## Adapter compile contract\n\n"
    text += table(
        ["AdapterCompile field", *names],
        [
            [f"`{field.name}`", *[value(getattr(profile.adapter_compile, field.name)) for profile in profiles]]
            for field in fields(profiles[0].adapter_compile)
        ],
    )
    for profile in profiles:
        text += f"## Resource domains: `{profile.name}`\n\n"
        domain_fields = fields(next(iter(profile.domains.values())))
        text += table(
            ["Domain", *[f"`{field.name}`" for field in domain_fields]],
            [
                [f"`{name}`", *[value(getattr(domain, field.name)) for field in domain_fields]]
                for name, domain in sorted(profile.domains.items())
            ],
        )
        text += f"## Layout atoms: `{profile.name}`\n\n"
        text += table(
            ["Atom", "Declared expansion"],
            [
                [f"`{name}`", f"`{json.dumps(atom, ensure_ascii=False, sort_keys=True)}`"]
                for name, atom in sorted(profile.atoms.items())
            ],
        )
    return text


def main() -> None:
    outputs = {
        "clauses.md": clauses(),
        "profiles.md": profiles(),
    }
    for name, content in outputs.items():
        path = HERE / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            print(f"unchanged docs/reference/{name}")
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote docs/reference/{name}")


if __name__ == "__main__":
    main()
